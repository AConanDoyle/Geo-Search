-- Target table for earthquakes
CREATE TABLE IF NOT EXISTS earthquakes (
    id          text PRIMARY KEY,
    place       text,
    mag         real,
    depth_km    real,
    event_time  timestamptz NOT NULL,
    updated     timestamptz NOT NULL,
    url         text,
    geom        geometry(Point, 4326) NOT NULL
);

CREATE INDEX IF NOT EXISTS earthquakes_geom_idx ON earthquakes USING gist (geom);
CREATE INDEX IF NOT EXISTS earthquakes_time_idx ON earthquakes (event_time DESC);

CREATE EXTENSION IF NOT EXISTS ogr_fdw;
CREATE EXTENSION IF NOT EXISTS pg_cron;

-- The USGS feed (last 24 h, refreshed about once a minute) as a foreign table.
-- GDAL downloads and parses the GeoJSON on every query; layer name = file name.
CREATE SERVER IF NOT EXISTS usgs
    FOREIGN DATA WRAPPER ogr_fdw
    OPTIONS (
        datasource 'https://earthquake.usgs.gov/earthquakes/feed/v1.0/summary/all_day.geojson',
        format 'GeoJSON',
        config_options 'GDAL_HTTP_TIMEOUT=30 GDAL_HTTP_CONNECTTIMEOUT=10'
    );

CREATE FOREIGN TABLE IF NOT EXISTS usgs_feed (
    id          varchar,
    mag         double precision,
    place       varchar,
    event_ms    bigint  OPTIONS (column_name 'time'),     -- milliseconds since epoch
    updated_ms  bigint  OPTIONS (column_name 'updated'),
    url         varchar,
    type        varchar,
    geom        geometry(PointZ, 4979)                    -- z = depth in km
) SERVER usgs OPTIONS (layer 'all_day');

-- Upsert new and revised earthquakes; returns how many rows changed.
CREATE OR REPLACE FUNCTION load_quakes(min_mag double precision DEFAULT 2.5)
RETURNS integer LANGUAGE sql AS $$
    WITH up AS (
        INSERT INTO earthquakes (id, place, mag, depth_km, event_time, updated, url, geom)
        SELECT DISTINCT ON (id)
               id, place, mag, ST_Z(geom),
               to_timestamp(event_ms / 1000.0), to_timestamp(updated_ms / 1000.0), url,
               ST_SetSRID(ST_Force2D(geom), 4326)
        FROM usgs_feed
        WHERE type = 'earthquake' AND mag >= min_mag AND geom IS NOT NULL
        ORDER BY id, updated_ms DESC
        ON CONFLICT (id) DO UPDATE SET
            place = EXCLUDED.place, mag = EXCLUDED.mag, depth_km = EXCLUDED.depth_km,
            updated = EXCLUDED.updated, url = EXCLUDED.url, geom = EXCLUDED.geom
        WHERE earthquakes.updated < EXCLUDED.updated
        RETURNING 1
    )
    SELECT count(*)::integer FROM up
$$;

-- Tell listeners (the API) about every new or revised quake
CREATE OR REPLACE FUNCTION notify_quake() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    PERFORM pg_notify('quake', NEW.id);
    RETURN NULL;
END
$$;

DROP TRIGGER IF EXISTS earthquakes_notify ON earthquakes;
CREATE TRIGGER earthquakes_notify
    AFTER INSERT OR UPDATE ON earthquakes
    FOR EACH ROW EXECUTE FUNCTION notify_quake();

-- CronJob, run import every minute
SELECT cron.schedule('load-quakes', '* * * * *', 'SELECT load_quakes()');